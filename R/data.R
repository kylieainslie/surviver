#'
#' @source Mossong J, et al. (2008) Social contacts and mixing patterns
#'   relevant to the spread of infectious diseases. *PLoS Med* 5(3):e74.
#'   Computed with [socialmixr::contact_matrix()]; see
#'   `data-raw/polymod_nl.R`.
