#' Simulated ground-truth data for time-varying vaccine effectiveness
#'
#' Two scenarios simulated with the HERMES individual-based model (waning-VE
#' extension) in which the true vaccine effectiveness as a function of time
#' since vaccination, VE(t), is known. Both use the same synthetic population
#' of 10,000 people, a slowed influenza-like epidemic over 180 days, and a
#' rolling vaccination campaign (16 ten-day rounds from day 21, each
#' vaccinating 3% of the remaining eligible population). They differ only in
#' the VE curve:
#'
#' * `ve_sim_waning`: VE rises linearly to 0.8 over 14 days, then decays
#'   exponentially (half-life 45 days) towards a floor of 0.1.
#' * `ve_sim_no_waning`: VE rises linearly to 0.8 over 14 days, then stays
#'   at 0.8.
#'
#' The two runs are not paired realisations of one epidemic: transmission is
#' random and diverges between them from the start.
#'
#' @format Each is a list with elements:
#' \describe{
#'   \item{demographic}{Data frame, one row per individual: `ind_id`, `age`,
#'     `sex`, `hh_id`, `classroom_id`, `workplace_id`.}
#'   \item{vaccination}{Data frame, one row per vaccinated individual:
#'     `ind_id`, `time_of_vaccination` (study day).}
#'   \item{incidence}{Data frame, one row per reported case: `ind_id`,
#'     `time_of_reporting` (study day; includes a reporting delay, so can
#'     exceed `study_end`). About 10% of symptomatic cases are unreported.}
#'   \item{params}{List of HERMES parameters used. The true VE(t) is defined
#'     by `vaccine_effectiveness` (peak), `ve_ramp_days`, `ve_half_life` and
#'     `ve_floor`.}
#'   \item{study_end}{Length of the study in days (180).}
#'   \item{hermes_commit}{Commit of `ibm_hermes` that generated the data.}
#' }
#'
#' @details Some vaccinated individuals were reported as cases before their
#'   vaccination date, because HERMES vaccinates from the whole eligible
#'   population, including people already infected.
#'
#' @source Generated by `data-raw/ve_test_scenarios.R` using
#'   <https://github.com/kylieainslie/ibm_hermes> (branch
#'   `waning-vaccine-effectiveness`).
#' @name ve_sim
NULL

#' @rdname ve_sim
"ve_sim_waning"

#' @rdname ve_sim
"ve_sim_no_waning"

